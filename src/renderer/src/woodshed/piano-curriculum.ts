const all: Lesson[] = []
function unit(
  level: 1 | 2 | 3,
  category: string,
  title: string,
  goal: string,
  explanation: string,
  example: string,
  steps: string,
  mistakes: string,
  check: string,
  easier: string,
  harder: string,
  preset: string
): void {
  const id = `piano-${all.length + 1}`,
    previous = all.at(-1)
  if (previous) previous.related.push(id)
  all.push({
    id,
    track: 'piano',
    category,
    level,
    title,
    goal,
    explanation,
    example,
    steps: steps.split('|'),
    mistakes,
    check,
    easier,
    harder,
    prerequisites: previous ? [previous.id] : [],
    related: [],
    exercise: {},
    workshopPreset: preset
  })
}
