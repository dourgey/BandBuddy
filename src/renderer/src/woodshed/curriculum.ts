const all: Lesson[] = []
function unit(
  track: Lesson['track'],
  number: number,
  category: string,
  level: 1 | 2 | 3,
  title: string,
  goal: string,
  explanation: string,
  example: string,
  steps: string,
  mistakes: string,
  check: string,
  easier: string,
  harder: string,
  exercise: Partial<ExerciseConfig> = {},
  technique?: Technique,
  view: Lesson['view'] = 'tab'
): void {
  const id = `${track}-${number}`
  const previous = all
    .filter((x) => x.track === track && (track !== 'shared' || x.category === category))
    .at(-1)
  const prerequisites = previous ? [previous.id] : track !== 'shared' ? ['shared-1'] : []
  const lesson: Lesson = {
    id,
    track,
    category,
    level,
    title,
    goal,
    explanation,
    example,
    steps: steps.split('|'),
    mistakes,
    check,
    easier,
    harder,
    prerequisites,
    related: [],
    exercise,
    technique,
    view
  }
  if (previous) previous.related.push(id)
  all.push(lesson)
}
