export function practiceTuning(instrument: Instrument): Tuning {
  return TUNINGS.find(t => t.id === (instrument === 'ukulele' ? 'uke-high' : instrument))!
}

// Each token is string:fret, joined by + for simultaneous notes; /duration is in quarter-note beats.
// A dash is a real rest. These authored scores are the single source for notation and highlighting.
export function practiceScore(instrument: Instrument, text: string, meter: PracticeMeter = '4/4'): { events: MusicEvent[]; beats: number; meter: PracticeMeter } {
  const tuning = practiceTuning(instrument)
  const beatsPerBar = Number(meter.split('/')[0])
  let beat = 0
  const events = text.trim().split(/\s+/).map((token, index): MusicEvent => {
    const [value, length = '1', articulation] = token.split('/')
    const duration = length === 't' ? 1 / 3 : length === 's' ? 2 / 3 : Number(length)
    const notes = value === '-' ? [] : value!.split('+').map(p => {
      const [string, fret] = p.split(':').map(Number)
      if (!Number.isInteger(string) || !string || string > tuning.notes.length || !Number.isInteger(fret) || fret === undefined || fret < 0 || fret > tuning.frets) throw new Error(`无效练习位置 ${p}`)
      return { string, fret, midi: tuning.notes[tuning.notes.length - string]! + fret }
    })
    if (![1 / 3, 2 / 3, 0.25, 0.5, 0.75, 1, 1.5, 2, 3, 4].some(d => Math.abs(d - duration) < 1e-9) || (beat % beatsPerBar) + duration > beatsPerBar + 1e-6) throw new Error(`无效谱例时值 ${token}`)
    if (articulation && !['bend', 'hammer', 'pull', 'slide', 'up', 'down', 'mute', 'vibrato'].includes(articulation)) throw new Error(`无效演奏法 ${articulation}`)
    const event: MusicEvent = { id: `practice-${index}`, beat, duration, notes }
    if (articulation === 'bend') event.bend = 2
    else if (articulation) event.technique = articulation as Technique
    beat = Math.round((beat + duration) * 12) / 12
    return event
  })
  if (beat % beatsPerBar !== 0) throw new Error(`练习谱例必须包含完整的 ${meter} 小节`)
  return { events, beats: beat, meter }
}
