/** Event remains active for its written duration, including across metronome pulses. */
export function practiceFrame(variant: PracticeVariant, beat: number): { event: MusicEvent | undefined; bar: number; pulse: number } {
  const position = ((beat % variant.beats) + variant.beats) % variant.beats
  const beatsPerBar = Number(variant.meter.split('/')[0])
  return { event: variant.events.find(e => position >= e.beat && position < e.beat + e.duration), bar: Math.floor(position / beatsPerBar) + 1, pulse: Math.floor(position % beatsPerBar) }
}
