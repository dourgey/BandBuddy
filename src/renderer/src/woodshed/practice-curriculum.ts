function add(instrument: Instrument, id: string, module: string, title: string, bpm: number,
  variants: VariantSeed[], explanation: string, milestones: [string, string, string], knowledge: string[] = []): void {
  all.push({ id: `${instrument}-${id}`, instrument, module, title, bpm,
    variants: variants.map(([name, description, score, meter]) => ({ name, description, ...practiceScore(instrument, score, meter) })),
    explanation, milestones, knowledge: knowledge.map(k => /^\d+-\d+$/.test(k) ? `guitar-outline-${k}` : k) })
}
