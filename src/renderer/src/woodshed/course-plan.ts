import type { Lesson } from './types.js'
import { ELECTRIC_COURSE } from './electric-curriculum.js'
export interface CourseChapter {
  id: string
  title: string
  lessonIds: string[]
  concept: string
  example: string
  listen: string
  drills: [string, string, string]
  diagnosis: string
  transfer: string
}
export interface CoursePlan {
  intro: string
  chapters: CourseChapter[]
}
function chapter(
  track: Lesson['track'],
  index: number,
  first: number,
  last: number,
  title: string,
  concept: string,
  example: string,
  listen: string,
  drills: [string, string, string],
  diagnosis: string,
  transfer: string
): CourseChapter {
  return {
    id: `${track}-chapter-${index}`,
    title,
    lessonIds: Array.from({ length: last - first + 1 }, (_, i) => `${track}-${first + i}`),
    concept,
    example,
    listen,
    drills,
    diagnosis,
    transfer
  }
}
