import type { Instrument } from './theory.js'
import type { VariantSeed } from './practice-curriculum.js'

interface Seed {
  instrument: Instrument; id: string; module: string; title: string; bpm: number
  variants: VariantSeed[]; explanation: string; milestones: [string, string, string]; knowledge: string[]
}
const seeds: Seed[] = []
function add(instrument: Instrument, id: string, title: string, bpm: number, variants: VariantSeed[], explanation: string, milestones: [string, string, string], knowledge: string[], module = ''): void {
  seeds.push({ instrument, id, title, bpm, variants, explanation, milestones, knowledge, module })
}
const bass = (id: string, title: string, bpm: number, variants: VariantSeed[], explanation: string, milestones: [string, string, string], ...nodes: number[]) => add('bass', id, title, bpm, variants, explanation, milestones, nodes.map(n => `bass-${n}`))
const uke = (id: string, title: string, bpm: number, variants: VariantSeed[], explanation: string, milestones: [string, string, string], ...nodes: number[]) => add('ukulele', id, title, bpm, variants, explanation, milestones, nodes.map(n => `ukulele-${n}`))

