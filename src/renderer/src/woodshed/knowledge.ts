function foundationStages(id: 'shared' | 'blues'): KnowledgeStage[] {
  const groups: [string, number[]][] = id === 'shared' ? [
    ['音高与基本动作', [1, 2, 3, 4, 5, 6]], ['节奏与读谱', [7, 8, 9]],
    ['指板与音阶', [10, 11, 12, 13, 14, 15]], ['模进与音乐组织', [16, 17, 18]],
    ['和声与声部', [19, 20, 21]], ['听觉与即兴', [22, 23, 24]]]
    : [['曲式与时间感', [1, 2, 3]], ['音阶与表达', [4, 5, 6]], ['句法与连接', [7, 8, 9]], ['完整演奏与变化', [10, 11, 12]]]
  return groups.map(([title, ids]) => ({ title, nodes: ids.map(number => {
    const l = LESSONS.find(l => l.id === `${id}-${number}`)!
    return { id: l.id, title: l.title, paragraphs: [l.explanation.replace('本工作台会明确显示 BPM 拍单位。', '标记 BPM 时，应同时注明它对应四分音符还是附点四分音符。').replace('这里指板与调音器始终显示实际发声音高。', '本文音名后标注的八度数字表示实际发声音高。').replace('图中品位按变调夹后的相对位置显示。', '使用变调夹时，需要区分相对品位与实际品位。')], example: l.example.replace('本工作台', '典型').replace('小调预设', '小调示例'), note: l.mistakes }
  }) }))
}

