import type { Lesson } from './types.js'
import type { Workshop } from './ensemble.js'
const lessons: Lesson[] = []
/** Each row is an original lesson, not a transposed or faster duplicate. */
function add(
  track: Workshop,
  category: string,
  level: 1 | 2 | 3,
  title: string,
  goal: string,
  explanation: string,
  example: string,
  steps: string,
  mistakes: string,
  check: string,
  easier: string,
  harder: string,
  preset: string
): void {
  const previous = lessons.filter((l) => l.track === track).at(-1),
    id = `${track}-${lessons.filter((l) => l.track === track).length + 1}`
  if (previous) previous.related.push(id)
  lessons.push({
    id,
    track,
    category,
    level,
    title,
    goal,
    explanation,
    example,
    steps: steps.split('|'),
    mistakes,
    check,
    easier,
    harder,
    prerequisites: previous ? [previous.id] : [],
    related: [],
    exercise: {},
    workshopPreset: preset
  })
}
