const all: Lesson[] = []
function unit(
  track: Lesson['track'],
  number: number,
  title: string,
  goal: string,
  explanation: string,
  example: string,
  steps: string,
  mistakes: string,
  check: string,
  easier: string,
  harder: string,
  prerequisites: string[],
  exercise: Partial<ExerciseConfig> = {},
  workshopPreset?: string
): void {
  all.push({
    id: `${track}-${number}`,
    track,
    category: '专题应用',
    level: 3,
    title,
    goal,
    explanation,
    example,
    steps: steps.split('|'),
    mistakes,
    check,
    easier,
    harder,
    prerequisites,
    related: [],
    exercise,
    workshopPreset
  })
}
